"""The G1 probe transcripts (SPEC §5.2), kept apart from `probe.py`'s scoring logic
purely for readability — these are long by requirement, not by accident.

**Why they are long: a single-chunk probe cannot test what G1 exists to test.**
SPEC §5.2 asks whether external memory lets "a LATER CHUNK overturn an earlier
conclusion". An earlier version of these transcripts was ~120 tokens, which at the
production budget (`chunker.CHUNK_TOKENS` = 2500) is ONE chunk — so no memory ever
crossed a step boundary, `DROP` was never exercised, and the agent arm was structurally
indistinguishable from a one-shot summariser. Every G1 number measured against those
transcripts was measuring something other than the mechanism (measured 2026-08-27;
`tests/test_probe.py::test_probe_transcripts_span_multiple_chunks` now pins this so the
defect cannot silently return).

**Why the planted topic dominates the transcript.** The first attempt at a fix spliced
the short planted arc into a real translated pilot meeting to reach multi-chunk length.
That failed differently and just as uninformatively: the planted arc was ~0.7% of the
transcript, competing against a dozen genuine agenda items for 16 memory slots, and the
model never recorded it at all — memory was not even at cap, so this was a salience
judgement, not a revision failure. A probe whose planted content loses on salience
measures salience, not revision. Here the arc IS the meeting's main business, so it
earns its memory slots on merit and any failure to revise is unambiguous.

Both scenarios therefore run: substantive discussion → decision → sustained unrelated
(but on-agenda) business → a procedural distractor → new information → explicit
reversal. Hand-written, not generated: a generated transcript would let the generator's
assumptions leak into what "passing" means.
"""

